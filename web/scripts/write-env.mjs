// Writes src/environments/env.generated.ts from env vars (git-ignored).
// Locally: values from web/.env. On App Hosting: values from apphosting.yaml (availability: BUILD).
// All values here end up in the browser. Only put browser-safe values here (PLAN.md 12).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const fileVars = {};
if (existsSync('.env')) {
  for (const line of readFileSync('.env', 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) fileVars[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const get = (k, fallback = '') => process.env[k] ?? fileVars[k] ?? fallback;

const env = {
  firebase: {
    apiKey: get('FIREBASE_API_KEY'),
    authDomain: get('FIREBASE_AUTH_DOMAIN'),
    projectId: get('FIREBASE_PROJECT_ID', 'demo-trip-planner'),
    appId: get('FIREBASE_APP_ID'),
  },
  mapsBrowserKey: get('MAPS_BROWSER_KEY'),
  apiBaseUrl: get('API_BASE_URL', 'http://localhost:8080'),
  recaptchaSiteKey: get('RECAPTCHA_SITE_KEY'),
  useEmulators: get('USE_EMULATORS', 'false') === 'true',
};

writeFileSync(
  'src/environments/env.generated.ts',
  `// Generated by scripts/write-env.mjs. Do not edit or commit.\nexport const env = ${JSON.stringify(env, null, 2)} as const;\n`,
);
console.log(`env.generated.ts written (project: ${env.firebase.projectId}, emulators: ${env.useEmulators})`);
